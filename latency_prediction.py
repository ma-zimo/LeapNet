import scienceplots
import seaborn as sns
import random
import numpy as np
import scipy.io as io

import matplotlib
import matplotlib.pyplot as plt
matplotlib.rcParams["axes.linewidth"] = 2

colors = sns.color_palette("Blues", 100)
random.seed(666)
np.random.seed(666)

import pandas as pd

raw_data = pd.read_excel("./policy_inference_data_resnet18.xlsx", converters={"policy": str})
raw_data = raw_data.to_numpy()

policy_list = []
latency_list = []

for item in raw_data:
    policy_list.append(item[0])
    latency_list.append(sum(item[1:])/len(item[1:]))
latency_list_final = np.array(latency_list)

policy_list_final = []
for policy in policy_list:
    policy_new = [int(i) for i in policy]
    policy_list_final.append(policy_new)
policy_list_final = np.array(policy_list_final)

# policy_list_final
#
# latency_list_final
#
# policy_list_final.shape, latency_list_final.shape

policy_list_final_shuffle = []
latency_list_final_shuffle = []

permutation = np.random.permutation(len(policy_list_final))

for i in permutation:
    policy_list_final_shuffle.append(policy_list_final[i])
    latency_list_final_shuffle.append(latency_list_final[i])

policy_list_final_shuffle = np.array(policy_list_final_shuffle)
latency_list_final_shuffle = np.array(latency_list_final_shuffle)

policy_list_final_shuffle.shape, latency_list_final_shuffle.shape

# mlp regression

from sklearn.neural_network import MLPRegressor

regr = MLPRegressor(random_state=123,
                    max_iter=1000,
                    hidden_layer_sizes=(64, 32),
                    learning_rate="constant",
                    learning_rate_init=0.001,
                    n_iter_no_change=100,
                    batch_size=8
                   ).fit(policy_list_final_shuffle, latency_list_final_shuffle)
latency_preds_list_mlp = regr.predict(policy_list_final_shuffle)
rmse_mlp = (sum((latency_preds_list_mlp - latency_list_final_shuffle) ** 2) / latency_list_final_shuffle.shape[0]) ** 0.5

weight_1, weight_2, weight_3 = regr.coefs_
bias_1, bias_2, bias_3 = regr.intercepts_

state_dict = {
    "weight_1": weight_1,
    "weight_2": weight_2,
    "weight_3": weight_3,
    "bias_1": bias_1,
    "bias_2": bias_2,
    "bias_3": bias_3
}
io.savemat("./latency_predictor_resnet18.mat", state_dict)

state_dict = io.loadmat("./latency_predictor_resnet18.mat")
weight_1 = state_dict["weight_1"]
weight_2 = state_dict["weight_2"]
weight_3 = state_dict["weight_3"]
bias_1 = state_dict["bias_1"]
bias_2 = state_dict["bias_2"]
bias_3 = state_dict["bias_3"]

out = np.matmul(policy_list_final_shuffle, weight_1) + bias_1
out = np.maximum(0, out)
out = np.matmul(out, weight_2) + bias_2
out = np.maximum(0, out)
out = np.matmul(out, weight_3) + bias_3
out = out.reshape(-1)


