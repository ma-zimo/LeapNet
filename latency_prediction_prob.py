def verify(p1=1.0, p2=1.0, p3=1.0, p4=1.0, p5=1.0, p6=1.0, p7=1.0, p8=1.0, regr_mlp=None, regr_linear=None,regr_svm=None,regr_sgd=None,regr_tree=None,regr_kernel=None):
    """
    E.g.,
    p1 is the keep prob
    p1_ is the drop prob
    """

    p1_ = 1 - p1 # 0
    p2_ = 1 - p2
    p3_ = 1 - p3
    p4_ = 1 - p4
    p5_ = 1 - p5
    p6_ = 1 - p6
    p7_ = 1 - p7
    p8_ = 1 - p8

    encoding_dict = {}
    latency_dict = {}
    probs_dict = {}
    latency_mea = 0. # measured mean latency

    for i1 in [0, 1]:
        for i2 in [0, 1]:
            for i3 in [0, 1]:
                for i4 in [0, 1]:
                    for i5 in [0, 1]:
                        for i6 in [0, 1]:
                            for i7 in [0, 1]:
                                for i8 in [0, 1]:
                                    encoding = [i1, i2, i3, i4, i5, i6, i7, i8]

                                    policy_str = ''.join(map(str, encoding))  # 将 policy 编码转换为字符串
                                    latency = latency_dict_actual.get(policy_str, 0)  # 使用实际延迟

                                    probs_1 = p1*i1 + p1_*(1-i1)
                                    probs_2 = p2*i2 + p2_*(1-i2)
                                    probs_3 = p3*i3 + p3_*(1-i3)
                                    probs_4 = p4*i4 + p4_*(1-i4)
                                    probs_5 = p5*i5 + p5_*(1-i5)
                                    probs_6 = p6*i6 + p6_*(1-i6)
                                    probs_7 = p7*i7 + p7_*(1-i7)
                                    probs_8 = p8*i8 + p8_*(1-i8)
                                    probs = probs_1 * probs_2 * probs_3 * probs_4 * probs_5 * probs_6 * probs_7 * probs_8
                                    probs_dict["{}{}{}{}{}{}{}{}".format(i1, i2, i3, i4, i5, i6, i7, i8)] = probs

                                    latency_mea += probs * latency

    latency_est_mlp = regr_mlp.predict([[p1, p2, p3, p4, p5, p6, p7, p8]]) # estimated latency
    latency_est_linear = regr_linear.predict([[p1, p2, p3, p4, p5, p6, p7, p8]])  # estimated latency
    latency_est_svm = regr_svm.predict([[p1, p2, p3, p4, p5, p6, p7, p8]])  # estimated latency
    latency_est_sgd = regr_sgd.predict([[p1, p2, p3, p4, p5, p6, p7, p8]])  # estimated latency
    latency_est_tree = regr_tree.predict([[p1, p2, p3, p4, p5, p6, p7, p8]])  # estimated latency
    latency_est_kernel = regr_kernel.predict([[p1, p2, p3, p4, p5, p6, p7, p8]])  # estimated latency

    return latency_est_mlp[0], latency_est_linear[0],latency_est_svm[0],latency_est_sgd[0],latency_est_tree[0], latency_est_kernel[0], latency_mea

