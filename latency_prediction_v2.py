import torch
import torch.nn as nn

class Predictor(nn.Module):
    """"""
    def __init__(self):
        super(Predictor, self).__init__()
        self.pred = nn.Sequential(
            nn.Linear(8, 64, bias=True),
            nn.ReLU(inplace=True),
            nn.Linear(64, 32, bias=True),
            nn.ReLU(inplace=True),
            nn.Linear(32, 1, bias=True)
        )

    def forward(self, x):
        return self.pred(x)

